/**
 * Interactive setup for the print notebook: signs in as the owner over HTTPS, steps up, registers
 * a `print_agent` device, optionally enables printing in POS Settings, and writes `.env` next to
 * the agent (mode 0o600, never logged).
 *
 *   pnpm --filter @sds/print-agent setup
 *   node agent.mjs --setup
 */
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createInterface } from 'node:readline/promises';
import { Writable } from 'node:stream';
import type { RegisterDeviceResponse, SessionResponse } from '@sds/shared';

const DEFAULT_API_URL = 'https://161-118-211-42.sslip.io';
const DEFAULT_DEVICE_NAME = 'Print notebook';

export function createPrompter() {
  let muted = false;
  const output = new Writable({
    write(chunk, _encoding, done) {
      if (!muted) process.stdout.write(chunk);
      done();
    },
  });
  const rl = createInterface({ input: process.stdin, output, terminal: true });
  return {
    async ask(question: string): Promise<string> {
      muted = false;
      return (await rl.question(question)).trim();
    },
    async askHidden(question: string): Promise<string> {
      process.stdout.write(question);
      muted = true;
      const answer = await rl.question('');
      muted = false;
      process.stdout.write('\n');
      return answer.trim();
    },
    close: () => rl.close(),
  };
}

export interface SetupApiDeps {
  baseUrl: string;
  fetchFn?: typeof fetch;
}

async function postJson<T>(
  deps: SetupApiDeps,
  path: string,
  body: unknown,
  sessionToken?: string,
): Promise<{ status: number; data: T }> {
  const fetchFn = deps.fetchFn ?? fetch;
  const headers: Record<string, string> = {
    'content-type': 'application/json',
    accept: 'application/json',
  };
  if (sessionToken) headers.authorization = `Bearer ${sessionToken}`;
  const response = await fetchFn(`${deps.baseUrl}${path}`, {
    method: 'POST',
    headers,
    body: JSON.stringify(body),
  });
  const text = await response.text();
  const data = (text ? JSON.parse(text) : {}) as T;
  return { status: response.status, data };
}

export function buildEnvFileContent(options: {
  apiBaseUrl: string;
  deviceToken: string;
  printerHost: string;
  widthDots?: number;
}): string {
  const width = options.widthDots ?? 576;
  return [
    '# @sds/print-agent configuration (generated by --setup; keep secret, never commit)',
    `PRINT_API_URL=${options.apiBaseUrl}`,
    `PRINT_DEVICE_TOKEN=${options.deviceToken}`,
    `PRINTER_HOST=${options.printerHost}`,
    'PRINTER_PORT=9100',
    `PRINTER_WIDTH_DOTS=${width}`,
    'PRINTER_TIMEOUT_MS=12000',
    'PRINTER_STATUS_CHECK=false',
    'POLL_INTERVAL_MS=2000',
    'HTTP_TIMEOUT_MS=10000',
    'PRINTED_JOBS_FILE=printed-jobs.json',
    'STOP_GRACE_MS=30000',
    '',
  ].join('\n');
}

function secondFactorField(code: string): { totp: string } | { recoveryCode: string } {
  return /^\d{6}$/.test(code) ? { totp: code } : { recoveryCode: code };
}

export async function runInteractiveSetup(envPath = resolve('.env')): Promise<number> {
  if (!process.stdin.isTTY) {
    console.error('Setup needs an interactive terminal to type owner credentials.');
    return 2;
  }

  const prompt = createPrompter();
  try {
    console.log('=== Saap Don Sen POS · Print Agent Setup ===\n');
    if (existsSync(envPath)) {
      const overwrite = await prompt.ask(`${envPath} already exists. Overwrite it? (y/N): `);
      if (!/^y(es)?$/i.test(overwrite)) {
        console.log('Cancelled. Nothing was changed.');
        return 0;
      }
    }

    const rawUrl = await prompt.ask(`POS API URL [${DEFAULT_API_URL}]: `);
    const baseUrl = (rawUrl || DEFAULT_API_URL).replace(/\/+$/, '');
    const deviceName =
      (await prompt.ask(`Device name [${DEFAULT_DEVICE_NAME}]: `)) || DEFAULT_DEVICE_NAME;
    const printerHost = (await prompt.ask('Printer connection [usb]: ')) || 'usb';

    const email = await prompt.ask('Owner e-mail: ');
    const password = await prompt.askHidden('Owner password (hidden): ');
    const code1 = await prompt.ask('6-digit authenticator code (or a recovery code) for sign-in: ');

    const deps: SetupApiDeps = { baseUrl };
    const login = await postJson<SessionResponse & { message?: string }>(deps, '/v1/auth/owner', {
      email,
      password,
      ...secondFactorField(code1),
    });
    if (login.status !== 200 || !login.data.sessionToken) {
      console.error(
        `Sign-in failed (HTTP ${login.status}): ${login.data.message ?? 'check credentials'}`,
      );
      return 1;
    }
    const sessionToken = login.data.sessionToken;
    console.log(`Signed in as ${login.data.staff.displayName}.`);

    try {
      let code2 = await prompt.ask(
        '\nWait for the NEXT 6-digit authenticator code (or enter a recovery code) for step-up: ',
      );
      while (code2 === code1 && /^\d{6}$/.test(code2)) {
        code2 = await prompt.ask(
          'That is the same 6-digit code just used. Wait a few seconds for the next code: ',
        );
      }

      const step = await postJson<{ stepUpUntil?: string; message?: string }>(
        deps,
        '/v1/auth/step-up',
        {
          password,
          ...secondFactorField(code2),
        },
        sessionToken,
      );
      if (step.status !== 200) {
        console.error(
          `Step-up failed (HTTP ${step.status}): ${step.data.message ?? 'invalid code'}`,
        );
        return 1;
      }

      const reg = await postJson<RegisterDeviceResponse & { message?: string }>(
        deps,
        '/v1/auth/device',
        { name: deviceName, kind: 'print_agent' },
        sessionToken,
      );
      if (reg.status !== 201 || !reg.data.deviceToken) {
        console.error(
          `Device registration failed (HTTP ${reg.status}): ${reg.data.message ?? 'error'}`,
        );
        return 1;
      }

      const content = buildEnvFileContent({
        apiBaseUrl: baseUrl,
        deviceToken: reg.data.deviceToken,
        printerHost,
      });
      writeFileSync(envPath, content, { encoding: 'utf8', mode: 0o600 });
      console.log(
        `\nRegistered "${reg.data.device.name}" (id: ${reg.data.device.id}) and saved ${envPath}.`,
      );

      // Offer to switch printing on right away if it is currently off.
      const enableAnswer = await prompt.ask(
        'Switch kitchen printing ON in POS Settings now? (Y/n): ',
      );
      if (enableAnswer === '' || /^y(es)?$/i.test(enableAnswer)) {
        const getRes = await fetch(`${baseUrl}/v1/settings/printing`, {
          headers: { authorization: `Bearer ${sessionToken}`, accept: 'application/json' },
        });
        if (getRes.ok) {
          const current = (await getRes.json()) as {
            version: number;
            value: { enabled: boolean };
          };
          if (current.value.enabled) {
            console.log('Kitchen printing is already ON.');
          } else {
            const patchRes = await fetch(`${baseUrl}/v1/settings/printing`, {
              method: 'PATCH',
              headers: {
                authorization: `Bearer ${sessionToken}`,
                'content-type': 'application/json',
                accept: 'application/json',
              },
              body: JSON.stringify({
                expectedVersion: current.version,
                value: { enabled: true },
              }),
            });
            if (patchRes.ok) console.log('Kitchen printing switched ON.');
            else console.warn(`Could not switch printing on (HTTP ${patchRes.status}).`);
          }
        }
      }
    } finally {
      await postJson(deps, '/v1/auth/logout', {}, sessionToken).catch(() => {});
    }

    console.log('\nSetup complete! Start the print agent with:');
    console.log('  pnpm --filter @sds/print-agent start');
    return 0;
  } finally {
    prompt.close();
  }
}
